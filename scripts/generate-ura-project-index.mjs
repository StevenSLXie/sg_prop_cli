#!/usr/bin/env node

import { readFile, writeFile } from "node:fs/promises";

const DEFAULT_SNAPSHOT = "research/market-pulse-index/output/normalized-snapshot.json";
const DEFAULT_OUTPUT = "src/ura-project-index.ts";

const args = parseArgs(process.argv.slice(2));
const snapshotPath = args.snapshot ?? DEFAULT_SNAPSHOT;
const outputPath = args.output ?? DEFAULT_OUTPUT;

const snapshot = JSON.parse(await readFile(snapshotPath, "utf8"));
const rows = Array.isArray(snapshot.rows) ? snapshot.rows : [];
const entries = new Map();

for (const row of rows) {
  const project = clean(row.project);
  const street = clean(row.street);
  const district = normalizeDistrict(row.district);
  if (!project || !street || !district) continue;
  entries.set(`${project}|${street}|${district}`, { project, street, district });
}

const sorted = [...entries.values()].sort(
  (left, right) => left.project.localeCompare(right.project) || left.street.localeCompare(right.street) || left.district.localeCompare(right.district)
);

const generatedAt = typeof snapshot.generated_at === "string" ? snapshot.generated_at : "unknown";
const content = `export type UraProjectIndexEntry = {
  project: string;
  street: string;
  district: string;
};

// Generated by scripts/generate-ura-project-index.mjs from URA PMI_Resi_Transaction snapshot ${generatedAt}.
// Keep this compact lookup committed so project/street-filtered analysis can prune URA batches before scanning.
export const URA_PRIVATE_SALE_PROJECT_INDEX: UraProjectIndexEntry[] = [
${sorted.map((entry) => `  ${JSON.stringify(entry)}`).join(",\n")}
];
`;

await writeFile(outputPath, content, "utf8");
console.log(
  JSON.stringify(
    {
      ok: true,
      snapshot: snapshotPath,
      output: outputPath,
      entries: sorted.length,
      generated_at: generatedAt
    },
    null,
    2
  )
);

function parseArgs(argv) {
  const parsed = {};
  for (let index = 0; index < argv.length; index++) {
    const arg = argv[index];
    if (!arg.startsWith("--")) continue;
    const key = arg.slice(2);
    const next = argv[index + 1];
    if (!next || next.startsWith("--")) parsed[key] = true;
    else {
      parsed[key] = next;
      index++;
    }
  }
  return parsed;
}

function clean(value) {
  return String(value ?? "")
    .trim()
    .replace(/\s+/g, " ");
}

function normalizeDistrict(value) {
  const number = Number(String(value ?? "").trim());
  return Number.isFinite(number) && number > 0 ? String(number).padStart(2, "0") : "";
}
